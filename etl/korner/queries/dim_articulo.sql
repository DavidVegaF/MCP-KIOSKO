SELECT a.ARTICULO_ID AS articulo_id,
       COALESCE((SELECT FIRST 1 TRIM(c.CLAVE_ARTICULO) FROM CLAVES_ARTICULOS c
                 WHERE c.ARTICULO_ID = a.ARTICULO_ID AND c.ROL_CLAVE_ART_ID = 17), 'SIN CLAVE') AS clave,
       TRIM(a.NOMBRE) AS nombre, TRIM(l.NOMBRE) AS linea, TRIM(g.NOMBRE) AS grupo,
       TRIM(a.ESTATUS) AS estatus, TRIM(a.ES_JUEGO) AS es_juego
FROM ARTICULOS a
LEFT JOIN LINEAS_ARTICULOS l ON l.LINEA_ARTICULO_ID = a.LINEA_ARTICULO_ID
LEFT JOIN GRUPOS_LINEAS g ON g.GRUPO_LINEA_ID = l.GRUPO_LINEA_ID
